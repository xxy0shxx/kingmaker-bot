func SearchRules(query, category string) []RuleEntry {
	q := strings.ToLower(strings.ReplaceAll(strings.TrimSpace(query), "ё", "е"))
	var out []RuleEntry
	for _, r := range PF2ERules {
		if category != "" && category != "all" && r.Category != category {
			continue
		}
		if q == "" {
			out = append(out, r)
			continue
		}
		titleNorm := strings.ToLower(strings.ReplaceAll(r.Title, "ё", "е"))
		if strings.Contains(titleNorm, q) {
			out = append(out, r)
			continue
		}
		for _, kw := range r.Keywords {
			if strings.Contains(q, kw) || strings.Contains(kw, q) {
				out = append(out, r)
				break
			}
		}
	}
	return out
}

func FindRuleByID(id string) *RuleEntry {
	for _, r := range PF2ERules {
		if r.ID == id {
			cp := r
			return &cp
		}
	}
	return nil
}
